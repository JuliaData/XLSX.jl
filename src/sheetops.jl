function copysheet!(ws::Worksheet, name::AbstractString="")::Worksheet
    wb = get_workbook(ws)
    is_chartsheet(wb, ws.name) && throw(XLSXError("Cannot copy a Chartsheet."))
    xl = get_xlsxfile(ws)
    _require_writable(ws, "copy a sheet")
    dim = get_dimension(ws)

    # make sure cache and XML are consistent
    update_worksheets_xml!(xl)

    ws.cache.is_full == true || throw(XLSXError("Cannot copy worksheet that does not have a full cache"))
    name = name == "" ? ws.name * " (copy)" : name

    new_ws = insertsheet!(wb, _copied_sheet_xml(ws), _copied_cache(ws), ws.sst_count, get_prefix(ws), name; dim)
    new_ws.unhandled_attributes = deepcopy(ws.unhandled_attributes)   # row styles, hidden rows, outline levels

    sheet_path = get_relationship_target_by_id("xl", wb, ws.relationship_id)
    new_sheet_path = get_relationship_target_by_id("xl", wb, new_ws.relationship_id)
    _copy_sheet_drawing!(xl, ws, new_ws, sheet_path, new_sheet_path)
    # The copy's <hyperlinks> came with the original's r:ids; give it relationships of its own.
    _copy_hyperlink_rels!(xl, sheet_path, new_sheet_path)

    # As in Excel, the copy's references to the original sheet are repointed at the
    # copy, in defined names, cell formulas, conditional formats and data validations;
    # references to other sheets are kept as they are.
    repoint = _renamed_sheet_ref(ws.name, new_ws.name)
    _repoint_sheet_xml_formulas!(new_ws, repoint)
    _copy_sheet_names_and_formulas!(wb, ws, new_ws, repoint)

    return new_ws
end

# A copy of the sheet's XML for its copy. The original stays the only selected
# sheet. References to parts the copy can't safely inherit are dropped: tables and
# legacy-drawing-backed comments belong to exactly one sheet in OOXML, and
# insertsheet! only wires up a "drawing" relationship for the new sheet, so any
# r:id in these elements would dangle. Duplicating and renaming those parts (table
# names must be workbook-unique, etc.) would be feature work of its own.
function _copied_sheet_xml(ws::Worksheet)::XML.Node
    xdoc = copynode(get_worksheet_xml_document(ws))
    root = xml_root_element(xdoc)
    for c in XML.children(root)
        localname(c) == "sheetViews" || continue
        for v in XML.children(c)
            localname(v) == "sheetView" && haskey(v, "tabSelected") && (v["tabSelected"] = "0")
        end
    end
    for tag in ("tableParts", "legacyDrawing", "legacyDrawingHF")
        idx = findfirst(c -> localname(c) == tag, XML.children(root))
        idx !== nothing && deleteat!(XML.children(root), idx)
    end
    return xdoc
end

# A deep copy of the sheet's full cache, so that writing to either sheet (values,
# formats, row heights) leaves the other alone.
_copied_cache(ws::Worksheet) = WorksheetCache(
    true,
    deepcopy(ws.cache.cells),
    copy(ws.cache.rows_in_cache),
    copy(ws.cache.row_ht),
    copy(ws.cache.row_index),
    SheetRowStreamIterator(ws), # Dummy - not needed because using full cache.
    nothing,
    ws.cache.dirty,
)

# Give the copy `new_ws` a drawing of its own, copied from the original's, if it has one.
function _copy_sheet_drawing!(xl::XLSXFile, ws::Worksheet, new_ws::Worksheet, sheet_path::AbstractString, new_sheet_path::AbstractString)
    drawing_path = _drawing_path_for_sheet(xl, sheet_path)
    drawing_path === nothing && return nothing

    # Pick a fresh drawing file name, and copy the drawing XML and rels verbatim
    i = 1
    while haskey(xl.data, "xl/drawings/drawing$i.xml"); i += 1; end
    new_drawing_file = "drawing$i.xml"
    new_drawing_path = "xl/drawings/$new_drawing_file"
    new_drawing_rels = _sheet_rels_path(new_drawing_path)
    xl.data[new_drawing_path]  = copynode(xl.data[drawing_path])
    xl.files[new_drawing_path] = true
    xl.data[new_drawing_rels]  = copynode(xl.data[_sheet_rels_path(drawing_path)])
    xl.files[new_drawing_rels] = true

    # A chart part belongs to one drawing, unlike media, so the copy needs its own.
    # Clone each and repoint the copied rels at the clone; otherwise both sheets
    # render the same chart part and editing either changes both.
    for n in elements_with_tag(xml_root_element(xl.data[new_drawing_rels]), "Relationship")
        t = get_attr(n, "Type")
        (t == REL_CHART || t == REL_CHARTEX) || continue
        get_attr(n, "TargetMode") == "External" && continue
        target = get_attr(n, "Target")
        old_t  = resolve_relative_target("xl/drawings", target)
        haskey(xl.data, old_t) || continue
        new_t  = clone_owned_part!(xl, old_t)
        t == REL_CHART   && repoint_chart_refs!(xl, new_t, ws.name, new_ws.name)
        t == REL_CHARTEX && repoint_chartex_refs!(xl, new_t, ws.name, new_ws.name)
        n["Target"] = _retarget(target, last(_split_zip_path(new_t)))
    end

    # Content types for the drawing and any media it references
    register_content_type!(xl, "[Content_Types].xml";
                           tag="Override", key="PartName", val="/$new_drawing_path",
                           content_type=MIME_DRAWING)
    for img in _images_for_drawing(xl, drawing_path, ws.name)
        ext = detect_image_ext(xl.binary_data["xl/media/$(img.media_name)"])
        ext_no_dot = String(lstrip(ext, '.'))
        register_content_type!(xl, "[Content_Types].xml";
                               tag="Default", key="Extension", val=ext_no_dot,
                               content_type=get(EXT_MIME, ext, "image/$ext_no_dot"))
    end

    # Link the drawing to the new sheet
    new_rels_path = _sheet_rels_path(new_sheet_path)
    if !haskey(xl.data, new_rels_path)
        xl.data[new_rels_path]  = empty_rels_doc()
        xl.files[new_rels_path] = true
    end
    new_rels_root = xml_root_element(xl.data[new_rels_path])
    rid = new_relationship_id(new_rels_root)
    push!(new_rels_root, XML.Element(prefixed_tag(get_prefix(new_rels_path, xl), "Relationship");
        Id=rid, Type=REL_DRAWING, Target="../drawings/$new_drawing_file",
    ))
    ensure_drawing_element!(xl, get_xml_data(xl, new_sheet_path), new_sheet_path, rid)
    return nothing
end

# Give the copy `new_ws` the original's sheet-scoped defined names and formulas,
# with references to the original repointed by `repoint`.
function _copy_sheet_names_and_formulas!(wb::Workbook, ws::Worksheet, new_ws::Worksheet, repoint)
    for k in [x for x in keys(wb.worksheet_names) if first(x) == ws.sheetId]
        dnv = wb.worksheet_names[k]
        val = if dnv.value isa DefinedNameRangeTypes && dnv.value.sheet == ws.name
            rename_sheet(dnv.value, new_ws.name)
        elseif dnv.value isa String && startswith(dnv.value, '=')
            replace(dnv.value, repoint)
        else
            dnv.value
        end
        wb.worksheet_names[(new_ws.sheetId, last(k))] = DefinedNameValue(val, copy(dnv.isabs), dnv.hidden)
    end
    for k in [x for x in keys(wb.formulas) if x.sheet == ws.name]
        f = copy(wb.formulas[k])
        f isa ExplicitFormula && (f.formula = replace(f.formula, repoint))
        wb.formulas[SheetCellRef(new_ws.name, k.cellref)] = f
    end
    new_ws.next_formula_id = ws.next_formula_id   # the copied shared formulas keep their ids
    return nothing
end

const REL_WORKSHEET   = "http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet"
const REL_CHARTSHEET  = "http://schemas.openxmlformats.org/officeDocument/2006/relationships/chartsheet"
const REL_CHART       = "http://schemas.openxmlformats.org/officeDocument/2006/relationships/chart"
const REL_CHARTEX     = "http://schemas.microsoft.com/office/2014/relationships/chartEx"
const MIME_WORKSHEET  = "application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"
const MIME_CHARTSHEET = "application/vnd.openxmlformats-officedocument.spreadsheetml.chartsheet+xml"
const MIME_CHART      = "application/vnd.openxmlformats-officedocument.drawingml.chart+xml"
const MIME_CHARTEX    = "application/vnd.ms-office.chartex+xml"

# Whether two sheet names are the same to Excel, which ignores case.
_same_sheetname(a::AbstractString, b::AbstractString) = uppercase(a) == uppercase(b)

# A sheet name Excel accepts: at most 31 characters, none of : \ / ? * [ ].
function check_valid_sheetname(n::AbstractString)
    max_length = 31
    if length(n) > max_length
        throw(XLSXError("Invalid sheetname $n: must have at most $max_length characters. Found $(length(n))"))
    end
    if occursin(r"[:\\/\?\*\[\]]+", n)
        throw(XLSXError("Sheetname cannot contain characters: ':', '\\', '/', '?', '*', '[' or ']'."))
    end
end

# The next GUID from the file's seeded `rng` (see `uuid_rng`) not already in `used`.
# The seed is fixed, so a reopened file replays the ids it was first written with;
# skipping those keeps output deterministic without duplicating an id.
function _unique_guid(rng::Random.AbstractRNG, used)::String
    while true
        id = "{" * uppercase(string(UUIDs.uuid4(rng))) * "}"
        id in used || return id
    end
end

# `xr:uid`s of the workbook's sheets, read from each root start tag only.
function _sheet_uids(wb::Workbook)::Set{String}
    xf = get_xlsxfile(wb)
    uids = Set{String}()
    for s in wb.sheets
        v = get(xf.data, get_relationship_target_by_id("xl", wb, s.relationship_id), nothing)
        isnothing(v) && continue
        root = v isa String ? xml_root_element(parse(v, XML.LazyNode)) : xml_root_element(v)
        uid = get(XML.attributes(root), "xr:uid", nothing)
        isnothing(uid) || push!(uids, uppercase(uid))
    end
    return uids
end

# Register `xdoc` as a new sheet: unique name, next sheetId, a free file in `dir`,
# the workbook relationship, the content-type override (for the file actually
# written), and <sheets>. Returns the Worksheet entry; the caller adds a cache
# if the sheet holds cells.
function _register_sheet!(wb::Workbook, xdoc::XML.Node, name::AbstractString;
                          dir::String, reltype::String, mime::String,
                          default_name::String, pfx::String = "",
                          dim::CellRange = CellRange("A1:A1"))::Worksheet
    xf = get_xlsxfile(wb)
    _require_writable(xf, "add a sheet")

    new_name = name
    existing = sheetnames(wb)
    i = 1
    while new_name == "" || any(n -> _same_sheetname(n, new_name), existing)
        new_name = (name == "" ? default_name : name * " ") * string(i)
        i += 1
    end
    check_valid_sheetname(new_name)

    sheetId = maximum((ws.sheetId for ws in wb.sheets); init = 0) + 1

    let root = xml_root_element(xdoc)
        haskey(root, "xmlns:xr") || (root["xmlns:xr"] = "http://schemas.microsoft.com/office/spreadsheetml/2014/revision")
        root["xr:uid"] = _unique_guid(wb.package.uuid_rng, _sheet_uids(wb))
    end

    j = 1
    while haskey(xf.files, "$dir/sheet$j.xml") || haskey(xf.data, "$dir/sheet$j.xml"); j += 1; end
    xml_filename = "$dir/sheet$j.xml"

    xf.files[xml_filename]     = true
    xf.data[xml_filename]      = xdoc
    xf.namespace[xml_filename] = pfx

    rId = add_relationship!(wb, xml_filename[4:end], reltype)
    ws  = Worksheet(xf, sheetId, rId, new_name, dim, :visible)
    push!(wb.sheets, ws)

    register_content_type!(xf, "[Content_Types].xml";
                           tag = "Override", key = "PartName", val = "/$xml_filename", content_type = mime)
    update_workbook_xml!(xf)
    return ws
end

function insertsheet!(wb::Workbook, xdoc::XML.Node, new_cache::WorksheetCache, sst_count::Int,
                      pfx::String, name::AbstractString = ""; dim = CellRange("A1:A1"))::Worksheet
    ws = _register_sheet!(wb, xdoc, name; dir = "xl/worksheets", reltype = REL_WORKSHEET,
                          mime = MIME_WORKSHEET, default_name = "Sheet", pfx, dim)
    ws.cache     = new_cache
    ws.sst_count = sst_count
    return ws
end

# Deletes `path` and, recursively, everything transitively reachable through
# its own `_rels` file — i.e. second/third/... order orphans. Used for parts
# that belong exclusively to one sheet (tables, comments, VML legacy drawings,
# and whatever those in turn reference, e.g. threaded comments off a comments
# part). Drawings/media are excluded by the caller and handled separately,
# since media can be reused across multiple drawings and needs a dedup check
# before deletion rather than unconditional removal.
function delete_part_and_orphans!(xf::XLSXFile, path::String)
    for store in (xf.files, xf.data, xf.binary_data)
        haskey(store, path) && delete!(store, path)
    end
    remove_override!(xf, "/$path")

    part_dir, part_file = rsplit(path, "/"; limit=2)
    part_rels = "$part_dir/_rels/$part_file.rels"
    if haskey(xf.data, part_rels)
        for node in elements_with_tag(xml_root_element(xf.data[part_rels]), "Relationship")
            get_attr(node, "TargetMode") == "External" && continue  # e.g. hyperlinks — not a package part
            target = resolve_relative_target(part_dir, get_attr(node, "Target"))
            delete_part_and_orphans!(xf, target)
        end
        for store in (xf.files, xf.data)
            haskey(store, part_rels) && delete!(store, part_rels)
        end
    end
end

add_override!(wb::Workbook, part::String, content::String) = add_override!(get_xlsxfile(wb), part, content)
function add_override!(xf::XLSXFile, part::String, content::String)
    ctype_root = xml_root_element(xmlroot(xf, "[Content_Types].xml"))
    XML.tag(ctype_root) != "Types" &&
        throw(XLSXError("Malformed `[Content_Types].xml`: its root element is `$(XML.tag(ctype_root))`, not `Types`."))
    override_node = XML.Element("Override";
        PartName=part,
        ContentType=content
    )
    push!(ctype_root, override_node)
    return nothing
end

remove_override!(wb::Workbook, part::String) = remove_override!(get_xlsxfile(wb), part)
function remove_override!(xf::XLSXFile, part::String)
    ctype_root = xml_root_element(xmlroot(xf, "[Content_Types].xml"))
    cont = XML.children(ctype_root)
    idx = findfirst(i -> haskey(cont[i], "PartName") && cont[i]["PartName"] == part, eachindex(cont))
    idx !== nothing && deleteat!(cont, idx)
    return nothing
end

# Keep bookViews' activeTab and firstSheet on the same sheet as sheets are deleted
# or moved. Both are 0-based positions in <sheets>, not relationship ids: `f` maps
# each old position to its new one, or to `nothing` to leave it as it is.
function _map_book_views!(f::Function, xf::XLSXFile)
    wbdoc = xmlroot(xf, "xl/workbook.xml")
    i, j  = get_idces(wbdoc, "workbook", "bookViews")
    isnothing(j) && return nothing
    for c in XML.children(wbdoc[i][j])
        localname(c) == "workbookView" || continue
        a = XML.attributes(c)
        isnothing(a) && continue
        for key in ("activeTab", "firstSheet")
            haskey(a, key) || continue
            t = f(parse(Int, a[key]))
            isnothing(t) || (c[key] = string(t))
        end
    end
    return nothing
end


