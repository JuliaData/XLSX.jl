               table7 7x2           B2:C8
               lookup 4x9           B2:J5
         header_error 3x4           B2:E4
       named_ranges_2 4x5           A1:E4
         named_ranges 14x6          A2:F15
```

"""
deletesheet!(ws::Worksheet) = deletesheet!(get_workbook(ws), ws.name)
deletesheet!(xl::XLSXFile, sheetId::Integer) = deletesheet!(get_workbook(xl), xl[sheetId].name)
deletesheet!(xl::XLSXFile, name::AbstractString) = deletesheet!(get_workbook(xl), name)
function deletesheet!(wb::Workbook, name::AbstractString)::XLSXFile
    hassheet(wb, name) || throw(XLSXError("Worksheet `$name` not found in workbook."))
    name = wb.sheets[_sheet_index(wb, name)].name    # the name as stored, whatever case was given
    sheetcount(wb) > 1 || throw(XLSXError("`$name` is this workbook's only sheet. Cannot delete the only sheet!"))
    ischart = is_chartsheet(wb, name)
    ischart || count(sh -> !is_chartsheet(wb, sh.name), wb.sheets) > 1 || throw(XLSXError(
        "`$name` is this workbook's only worksheet. A workbook must keep at least one, " *
        "even when it has chartsheets."))

    xf = get_xlsxfile(wb)

    # Locate the sheet by its relationship's actual target, before anything is removed.
    s          = findfirst(sh -> sh.name == name, wb.sheets)
    pos        = s - 1                                    # 0-based position in <sheets>
    sId        = wb.sheets[s].sheetId
    rId        = wb.sheets[s].relationship_id
    sheet_path = get_worksheet_internal_file(wb.sheets[s])

    # Relationship and sheet list. Ids are unique, so the type needn't be checked.
    r = findfirst(y -> y.Id == rId, wb.relationships)
    delete_relationships!(xf, wb.relationships[r])
    deleteat!(wb.relationships, r)
    deleteat!(wb.sheets, s)

    dead_xlchart = _delete_sheet_names!(wb, name, sId)
    _delete_sheet_parts!(xf, name, sheet_path)

    invalidate_chart_refs!(xf, name, dead_xlchart)
    update_formulas_missing_sheet!(wb, name)
    update_sheet_xml_formulas_missing_sheet!(wb, name)
    n = length(wb.sheets)   # the sheets after `pos` move up one
    _map_book_views!(t -> clamp(t > pos ? t - 1 : t, 0, n - 1), xf)
    update_workbook_xml!(xf)
    return xf
end

# The defined names, once sheet `name` (with sheetId `sId`) is deleted. As in Excel,
# a name that refers to the deleted sheet is kept as #REF!, except a chartEx chart's
# _xlchart names, which Excel drops along with the sheet: their values are returned,
# so the charts can be emptied to match. A name defined by a formula keeps the
# formula, with its references to the deleted sheet made #REF!. The sheet's own
# names go with it.
function _delete_sheet_names!(wb::Workbook, name::AbstractString, sId::Int)::Dict{String,String}
    missing_ref = _missing_sheet_ref(name)
    # A formula name with its references to the sheet made #REF!; `nothing` if it has none.
    function dead_formula_value(v)
        v.value isa String && startswith(v.value, '=') || return nothing
        s = replace(v.value, missing_ref)
        return s == v.value ? nothing : DefinedNameValue(s, v.isabs, v.hidden)
    end
    dead_xlchart = Dict{String,String}()
    for (k, v) in collect(wb.workbook_names)
        dv = dead_formula_value(v)
        isnothing(dv) || (wb.workbook_names[k] = dv; continue)
        v.value isa DefinedNameRangeTypes && v.value.sheet == name || continue
        if startswith(k, "_xlchart.")
            dead_xlchart[k] = string(v.value)
            delete!(wb.workbook_names, k)
        else
            wb.workbook_names[k] = DefinedNameValue("=#REF!", false, v.hidden)
        end
    end
    for (k, v) in collect(wb.worksheet_names)
        if first(k) == sId
            delete!(wb.worksheet_names, k)
        elseif v.value isa DefinedNameRangeTypes && v.value.sheet == name
            wb.worksheet_names[k] = DefinedNameValue("=#REF!", false, v.hidden)
        else
            dv = dead_formula_value(v)
            isnothing(dv) || (wb.worksheet_names[k] = dv)
        end
    end
    return dead_xlchart
end

# Remove the parts of deleted sheet `name`, at `sheet_path`, and their content types.
# Drawings and media keep their dedup-aware handling (media can be shared across
# drawings); everything else the sheet's rels hold belongs to this sheet alone and
# is removed recursively. Worksheets and chartsheets alike: a chartsheet's rels
# hold only its drawing.
function _delete_sheet_parts!(xf::XLSXFile, name::AbstractString, sheet_path::AbstractString)
    _delete_sheet_drawing!(xf, name, sheet_path)
    sheet_dir = first(_split_zip_path(sheet_path))
    sheet_rels = _sheet_rels_path(sheet_path)
    if haskey(xf.data, sheet_rels)
        for node in elements_with_tag(xml_root_element(xf.data[sheet_rels]), "Relationship")
            get_attr(node, "Type") == REL_DRAWING && continue
            get_attr(node, "TargetMode") == "External" && continue
            delete_part_and_orphans!(xf, resolve_relative_target(sheet_dir, get_attr(node, "Target")))
        end
    end
    for store in (xf.files, xf.data)
        delete!(store, sheet_rels)
    end
    for store in (xf.files, xf.data, xf.binary_data)
        delete!(store, sheet_path)
    end
    remove_override!(xf, "/$sheet_path")
    return nothing
end

function _delete_sheet_drawing!(xf::XLSXFile, name::AbstractString, sheet_path::AbstractString)
    drawing_path = _drawing_path_for_sheet(xf, sheet_path)
    drawing_path === nothing && return nothing
    drawing_rels = _sheet_rels_path(drawing_path)

    deleted_names = Set(img.media_name for img in _images_for_drawing(xf, drawing_path, name))
    still_used    = Set(img.media_name for img in getImages(xf) if img.sheet != name)
    for media_name in setdiff(deleted_names, still_used)
        delete!(xf.binary_data, "xl/media/$media_name")
    end

    if haskey(xf.data, drawing_rels)
        for n in elements_with_tag(xml_root_element(xf.data[drawing_rels]), "Relationship")
            get_attr(n, "Type") == REL_IMAGE && continue
            get_attr(n, "TargetMode") == "External" && continue
            delete_part_and_orphans!(xf, resolve_relative_target("xl/drawings", get_attr(n, "Target")))
        end
    end
    for path in (drawing_path, drawing_rels)
        delete!(xf.files, path)
        delete!(xf.data, path)
    end
    remove_override!(xf, "/$drawing_path")
    return nothing
end

_sheet_to_move(wb::Workbook, s::AbstractString) = getsheet(wb, String(s))
_sheet_to_move(::Workbook, s::Bool) =
    throw(XLSXError("A sheet must be given as a name, a position or a Worksheet, not `$s`."))
function _sheet_to_move(wb::Workbook, s::Integer)
    1 <= s <= sheetcount(wb) ||
        throw(XLSXError("$(get_xlsxfile(wb).source) has no sheet $s: it has $(sheetcount(wb)) sheet(s)."))
    return getsheet(wb, Int(s))
end
function _sheet_to_move(wb::Workbook, s::Worksheet)
    any(w -> w === s, wb.sheets) || throw(XLSXError("Worksheet `$(s.name)` is not in this workbook."))
    return s
end

"""
    movesheet!(ws::Worksheet; before=nothing, after=nothing) -> ::XLSXFile
    movesheet!(wb::Workbook, sheet; before=nothing, after=nothing) -> ::XLSXFile
    movesheet!(xf::XLSXFile, sheet; before=nothing, after=nothing) -> ::XLSXFile

Move a sheet to a new place in the workbook's tab order, immediately `before` or
`after` another sheet. Give exactly one of `before` or `after`.

The sheet to move and the sheet to place it next to may each be given as a
`Worksheet`, a sheet name or a 1-based tab position (as before the move). To move
a sheet to the start use `before=1`, and to the end use `after=sheetcount(xf)`.

Nothing in the workbook needs to be rewritten: formulas, charts and defined names
refer to sheets by name, and names scoped to a sheet stay with that sheet. The
active tab stays on the same sheet.

!!! note "Caution"

    As in Excel, a 3D reference such as `=SUM(Jan:Mar!A1)` covers whichever sheets
    lie between `Jan` and `Mar` in tab order, so moving a sheet into or out of that
    span changes the result.

See also [`addsheet!`](@ref), [`renamesheet!`](@ref), [`copysheet!`](@ref), [`deletesheet!`](@ref)

# Examples

```julia
julia> xf = XLSX.newxlsx("A"); XLSX.addsheet!(xf, "B"); XLSX.addsheet!(xf, "C");

julia> XLSX.movesheet!(xf, "C"; before="A");

julia> XLSX.sheetnames(xf)
3-element Vector{String}:
 "C"
 "A"
 "B"

julia> XLSX.movesheet!(xf[1]; after=XLSX.sheetcount(xf));

julia> XLSX.sheetnames(xf)
3-element Vector{String}:
 "A"
 "B"
 "C"
```

"""
movesheet!(ws::Worksheet; kw...) = movesheet!(get_workbook(ws), ws; kw...)
movesheet!(xf::XLSXFile, sheet; kw...) = movesheet!(get_workbook(xf), sheet; kw...)
function movesheet!(wb::Workbook, sheet; before=nothing, after=nothing)::XLSXFile
    isnothing(before) == isnothing(after) &&
        throw(XLSXError("Give exactly one of `before` or `after` to say where to move the sheet."))
    xf = get_xlsxfile(wb)
    _require_writable(xf, "move a sheet")
    ws     = _sheet_to_move(wb, sheet)
    target = _sheet_to_move(wb, something(before, after))
    ws === target && return xf

    old_order = copy(wb.sheets)
    deleteat!(wb.sheets, findfirst(w -> w === ws, wb.sheets))
    t = findfirst(w -> w === target, wb.sheets)
    insert!(wb.sheets, isnothing(before) ? t + 1 : t, ws)

    _map_book_views!(t -> 0 <= t < length(old_order) ? findfirst(s -> s === old_order[t + 1], wb.sheets) - 1 : nothing, xf)
    update_workbook_xml!(xf)
    return xf
end
