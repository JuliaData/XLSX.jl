"""
    renamesheet!(ws::Worksheet, name::AbstractString)

Rename a `Worksheet` to `name`.

See also [`addsheet!`](@ref), [`copysheet!`](@ref), [`deletesheet!`](@ref), [`movesheet!`](@ref)

"""
function renamesheet!(ws::Worksheet, name::AbstractString)

    xf = get_xlsxfile(ws)

    # no-op if the name has not changed
    if ws.name == name
        return
    end
    
    _require_writable(xf, "rename a sheet")
    # Excel compares sheet names case-insensitively; renaming a sheet to a new case of its own name is fine.
    any(s -> s !== ws && _same_sheetname(s.name, name), get_workbook(xf).sheets) &&
        throw(XLSXError("Sheetname $name is already in use."))
    isempty(name) && throw(XLSXError("A sheet name cannot be empty."))
    check_valid_sheetname(name)

    for p in (parts_with_content_type(xf, MIME_CHART)..., parts_with_content_type(xf, MIME_CHARTEX)...)
        repoint_chart_refs!(xf, p, ws.name, name)
    end

    # updates XML
    xroot = xml_root_element(xmlroot(xf, "xl/workbook.xml"))
    for node in XML.children(xroot)
        if localname(node) == "sheets"

            for sheet_node in xml_elements(node)
                if sheet_node["name"] == ws.name
                    # assign new name
                    sheet_node["name"] = name
                    break
                end
            end

            break
        end
    end

    update_formulas_renamed_sheet!(get_workbook(ws), ws.name, name)
    update_defined_names_renamed_sheet!(get_workbook(ws), ws.name, name)
    update_sheet_xml_formulas_renamed_sheet!(get_workbook(ws), ws.name, name)

    # updates the new name in the worksheet instance
    ws.name = name
    nothing
end

